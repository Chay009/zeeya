// Turns generated illustration PNGs into the app's art assets:
//   node scripts/build-art.mjs <source-dir>
// For every <name>.png in <source-dir> it trims the transparent margin,
// resizes (categories to 192px, section art to 480px — enough for a 3x
// screen at the sizes they are shown), writes assets/art/<name>.webp, and
// regenerates components/art/art-sources.ts from every .webp in
// assets/art, so the registry only ever references files that exist.
import { readdirSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function loadSharp() {
  try {
    return require("sharp");
  } catch {
    // Not a direct dependency: use the copy the Expo toolchain installs.
    const store = path.join(root, "..", "..", "node_modules", ".pnpm");
    const dir = readdirSync(store).find((name) => name.startsWith("sharp@"));
    if (!dir) throw new Error("sharp is not installed (pnpm add -D sharp)");
    return require(path.join(store, dir, "node_modules", "sharp"));
  }
}

const sharp = loadSharp();
const source = process.argv[2];
if (!source) throw new Error("usage: node scripts/build-art.mjs <source-dir>");

const outDir = path.join(root, "assets", "art");
mkdirSync(outDir, { recursive: true });

for (const file of readdirSync(source)
  .filter((name) => /^[a-z0-9-]+\.png$/.test(name))
  .sort()) {
  const name = file.replace(/\.png$/, "");
  const size = name.startsWith("cat-") ? 192 : 480;
  const target = path.join(outDir, `${name}.webp`);
  await sharp(path.join(source, file))
    .trim({ threshold: 1 })
    .resize(size, size, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .webp({ quality: 88, alphaQuality: 100, effort: 6 })
    .toFile(target);
  console.log(`${name}.webp  ${Math.round(statSync(target).size / 1024)} KB`);
}

// The registry lists every piece in assets/art, not just this batch — so a
// partial batch adds or replaces pieces without dropping the rest.
const names = readdirSync(outDir)
  .filter((name) => /^[a-z0-9-]+\.webp$/.test(name))
  .map((name) => name.replace(/\.webp$/, ""))
  .sort();
const lines = names.map((name) => `  "${name}": require("../../assets/art/${name}.webp"),`);
writeFileSync(
  path.join(root, "components", "art", "art-sources.ts"),
  `// Generated by scripts/build-art.mjs — do not edit by hand.\n` +
    `/* eslint-disable @typescript-eslint/no-require-imports */\n` +
    `export const ART_SOURCES = {\n${lines.join("\n")}\n} as const;\n`,
);
console.log(`${names.length} art assets`);
